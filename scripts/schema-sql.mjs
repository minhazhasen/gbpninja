// Writes prisma/schema.sql: the full schema as idempotent SQLite statements (CREATE … IF NOT EXISTS).
// The production server can't run the Prisma CLI, so src/instrumentation.ts runs this file on start-up to create missing tables.
// Run after changing prisma/schema.prisma (npm run db:sql); the deploy workflow regenerates it too.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const sql = execFileSync("npx", ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", "prisma/schema.prisma", "--script"], { encoding: "utf8" });
const idempotent = sql
  .replace(/CREATE TABLE "/g, 'CREATE TABLE IF NOT EXISTS "')
  .replace(/CREATE (UNIQUE )?INDEX "/g, (_, u) => `CREATE ${u ?? ""}INDEX IF NOT EXISTS "`);
writeFileSync("prisma/schema.sql", `-- Generated by scripts/schema-sql.mjs from prisma/schema.prisma. Do not edit.\n${idempotent}`);
console.log("Wrote prisma/schema.sql");
